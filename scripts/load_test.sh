#!/usr/bin/env bash
# Local load test. Needs the demo environment (scripts/demo.sh already run).
# Usage: scripts/load_test.sh [--monitors N] [--interval S] [--duration S] [--api-clients N]
# Writes the report to docs/evidencias/ensaio-de-carga.md.
set -euo pipefail

cd "$(dirname "$0")/.."
COMPOSE=(docker compose -f compose.yaml -f compose.demo.yaml --profile demo)
OUT=docs/evidencias/ensaio-de-carga.md
mkdir -p docs/evidencias
PULSEOPS_DEMO_PASSWORD="$(cat .demo/admin-password)"
export PULSEOPS_DEMO_PASSWORD

{
  echo "# Local load test"
  echo
  echo "Generated by \`scripts/load_test.sh $*\` on $(date -u +%Y-%m-%dT%H:%MZ)."
  echo "Commit: \`$(git rev-parse --short HEAD 2>/dev/null || echo unknown)\`."
  echo
  echo "## Machine"
  echo
  echo "- System: $(uname -srm)"
  echo "- Visible CPUs: $(nproc)"
  echo "- Total memory: $(awk '/MemTotal/ {printf "%.1f GiB", $2/1048576}' /proc/meminfo)"
  echo "- Docker: $(docker version --format '{{.Server.Version}}')"
  echo "- Worker: concurrency $("${COMPOSE[@]}" exec -T worker printenv PULSEOPS_WORKER_CONCURRENCY 2>/dev/null || echo '20 (default)')"
  echo
  echo "## Result"
  echo
} > "$OUT"

# CPU and memory sample of the containers in the middle of the measured window.
( sleep 70; docker stats --no-stream --format '| {{.Name}} | {{.CPUPerc}} | {{.MemUsage}} |' \
    > /tmp/pulseops-stats.txt ) &
STATS_PID=$!

"${COMPOSE[@]}" run --rm --no-deps -T demo-runner python scripts/load_test.py "$@" | tee -a "$OUT"
wait "$STATS_PID" || true

{
  echo
  echo "## Resource usage (single sample in the middle of the window)"
  echo
  echo "| Container | CPU | Memory |"
  echo "|---|---|---|"
  grep pulseops /tmp/pulseops-stats.txt || echo "| (no sample) | | |"
  echo
  echo "## How to read this"
  echo
  echo "The numbers hold for this machine, this configuration and this duration. They do not"
  echo "show maximum capacity or production behavior; the target is local and answers in a"
  echo "few milliseconds, which does not happen with real APIs."
} >> "$OUT"
echo "Report: $OUT"
